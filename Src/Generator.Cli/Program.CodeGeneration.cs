using System.Security.Cryptography;
using System.Text;
using static FastEndpoints.Generator.Cli.TypeNames;

namespace FastEndpoints.Generator.Cli;

partial class Program
{
    private static void WriteGeneratedOutput(string outputDir,
                                             string rootNamespace,
                                             HashSet<string> serializableTypes,
                                             bool includeTimestamp)
    {
        Directory.CreateDirectory(outputDir);

        var contextCode = GenerateSerializerContext(rootNamespace, serializableTypes, includeTimestamp);
        var contextPath = Path.Combine(outputDir, ContextFileName);
        File.WriteAllText(contextPath, contextCode, Encoding.UTF8);

        var extensionCode = GenerateExtensionMethod(rootNamespace, serializableTypes.Count > 0);
        var extensionPath = Path.Combine(outputDir, ExtensionsFileName);
        File.WriteAllText(extensionPath, extensionCode, Encoding.UTF8);

        Console.WriteLine("Generated files:");
        Console.WriteLine($"  {contextPath}");
        Console.WriteLine($"  {extensionPath}");
    }

    private static string GenerateSerializerContext(string rootNamespace, HashSet<string> types, bool includeTimestamp)
    {
        var b = new StringBuilder();

        b.l("// <auto-generated />");
        b.l("// Generated by FastEndpoints.Generator.Cli");

        if (includeTimestamp)
            b.l($"// Generated at: {DateTime.Now:yyyy-MM-dd HH:mm:ss}");

        //the stj generator rejects a context without any [JsonSerializable] types
        if (types.Count == 0)
        {
            b.l("// No serializable types were found in endpoints.");

            return b.ToString();
        }

        b.l("");
        b.l("#pragma warning disable");
        b.l("#nullable enable");
        b.l("");
        b.l("using System.Text.Json.Serialization;");
        b.l("");
        b.l($"namespace {rootNamespace};");
        b.l("");
        b.l("/// <summary>");
        b.l($"/// STJ serializer context for {rootNamespace} endpoints.");
        b.l("/// </summary>");

        var usedTypeInfoNames = new HashSet<string>(StringComparer.Ordinal);

        foreach (var type in types.OrderBy(t => t, StringComparer.Ordinal))
        {
            var globalStrippedType = StripGlobal(type);
            var typeInfoName = MakeTypeInfoPropertyName(type);
            var suffix = 1;

            while (!usedTypeInfoNames.Add(typeInfoName))
                typeInfoName = $"{MakeTypeInfoPropertyName(type)}_{ComputeStableShortHash(type + suffix++)}";

            b.l($"[JsonSerializable(typeof({globalStrippedType}), TypeInfoPropertyName = \"{typeInfoName}\")]");
        }

        b.l("internal partial class GeneratedSerializerContext : JsonSerializerContext;");

        return b.ToString();
    }

    private static string MakeTypeInfoPropertyName(string fullTypeName)
    {
        if (string.IsNullOrWhiteSpace(fullTypeName))
            return "TI_Unknown";

        var simpleName = SimpleName(fullTypeName).ToValidIdentifier();

        var hash = ComputeStableShortHash(fullTypeName);

        return $"TI_{simpleName}_{hash}";
    }

    private static string ComputeStableShortHash(string value)
    {
        var bytes = SHA256.HashData(Encoding.UTF8.GetBytes(value));

        return Convert.ToHexString(bytes, 0, 4);
    }

    private static string GenerateExtensionMethod(string rootNamespace, bool hasContext)
    {
        var sb = new StringBuilder();

        sb.l("// <auto-generated />");
        sb.l("// Generated by FastEndpoints.Generator.Cli");
        sb.l("");
        sb.l("#pragma warning disable");
        sb.l("#nullable enable");
        sb.l("");
        sb.l("using System.Text.Json;");
        sb.l("");
        sb.l($"namespace {rootNamespace};");
        sb.l("");
        sb.l("/// <summary>");
        sb.l("/// Extension methods for adding generated serializer contexts.");
        sb.l("/// </summary>");
        sb.l("public static class FastEndpointsSerializerExtensions");
        sb.l("{");
        sb.l("    /// <summary>");
        sb.l("    /// Adds the generated JSON serializer context to the JSON serializer options.");
        sb.l("    /// </summary>");
        sb.l($"    public static JsonSerializerOptions AddSerializerContextsFrom{rootNamespace.ToMethodSuffix()}(this JsonSerializerOptions options)");
        sb.l("    {");
        if (hasContext)
        {
            sb.l("        var context = new GeneratedSerializerContext(new(options));");
            sb.l("        options.TypeInfoResolverChain.Insert(0, context);");
            sb.l("");
        }

        sb.l("        return options;");
        sb.l("    }");
        sb.l("}");

        return sb.ToString();
    }
}
